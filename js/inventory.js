window.PAB = window.PAB || {};

PAB.formatPrice = function (n) {
  return "₱" + Number(n).toLocaleString("en-PH");
};

PAB.formatMileage = function (n) {
  return Number(n).toLocaleString("en-PH") + " km";
};

PAB.vehicleTitle = function (v) {
  return v.year + " " + v.make + " " + v.model;
};

PAB.getVehicle = function (id) {
  return (window.PAB_INVENTORY || []).find(function (v) {
    return v.id === id;
  });
};

PAB.getFeatured = function (limit) {
  var featured = (window.PAB_INVENTORY || []).filter(function (v) {
    return v.featured;
  });
  return featured.slice(0, limit || 6);
};

PAB.vehicleCardHTML = function (v) {
  var badge = v.badge
    ? '<span class="vehicle-card__badge">' + v.badge + "</span>"
    : "";
  return (
    '<a class="card vehicle-card" href="vehicle.html?id=' +
    encodeURIComponent(v.id) +
    '">' +
    '<div class="vehicle-card__media">' +
    badge +
    '<img src="' +
    v.images[0] +
    '" alt="' +
    PAB.vehicleTitle(v) +
    '" loading="lazy" width="640" height="400">' +
    "</div>" +
    '<div class="vehicle-card__body">' +
    '<div class="vehicle-card__title">' +
    PAB.vehicleTitle(v) +
    " " +
    (v.trim || "") +
    "</div>" +
    '<div class="vehicle-card__meta">' +
    PAB.formatMileage(v.mileage) +
    " · " +
    v.transmission +
    " · " +
    v.body +
    "</div>" +
    '<div class="vehicle-card__price">' +
    PAB.formatPrice(v.price) +
    "</div>" +
    "</div></a>"
  );
};

